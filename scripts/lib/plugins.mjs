// The plugins the manual documents, read from an AIDE checkout: the server plugins' whole manifests
// and scopes (`aide-plugins manifests`) and the device plugins' manifest.json under community/,
// leaving out the ones that exist only for AIDE's own tests.

import { execFileSync } from "node:child_process";
import { existsSync, readFileSync, readdirSync } from "node:fs";
import { join } from "node:path";

export const TEST_PLUGINS = ["hang-test", "rpc-test", "schedule-test"];

export function serverPlugins(aide) {
    const json = execFileSync("go", ["run", "./cmd/aide-plugins", "manifests"], {
        cwd: join(aide, "plugins"),
        encoding: "utf8",
    });
    return JSON.parse(json);
}

export function devicePlugins(aide) {
    const root = join(aide, "community");
    return readdirSync(root, { withFileTypes: true })
        .filter((entry) => entry.isDirectory() && !TEST_PLUGINS.includes(entry.name))
        .map((entry) => join(root, entry.name, "manifest.json"))
        .filter((path) => existsSync(path))
        .map((path) => JSON.parse(readFileSync(path, "utf8")))
        .sort((a, b) => a.id.localeCompare(b.id));
}

export function pluginsJson(aide) {
    const snapshot = {
        note: "Generated by scripts/sync-from-aide.mjs from AIDE's plugins. Do not edit.",
        server: serverPlugins(aide),
        device: devicePlugins(aide),
    };
    return `${JSON.stringify(snapshot, null, 4)}\n`;
}

/// The plugins added, removed or changed between two snapshots, sorted; a plugin is named by its id,
/// with "(device)" when it is a device plugin (Recall is both a server and a device plugin).
export function changedPlugins(before, after) {
    const byName = (snapshot) =>
        new Map([
            ...(snapshot.server ?? []).map((plugin) => [plugin.id, JSON.stringify(plugin)]),
            ...(snapshot.device ?? []).map((plugin) => [`${plugin.id} (device)`, JSON.stringify(plugin)]),
        ]);
    const old = byName(before);
    const now = byName(after);
    const names = new Set([...old.keys(), ...now.keys()]);
    return [...names].filter((name) => old.get(name) !== now.get(name)).sort();
}
